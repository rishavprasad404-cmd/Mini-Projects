print("============ Smart Shooping Cart System ============================")
cart = ["Milk", "Bread", "Eggs", "Butter", "Chesse"]
cart.append("Rice")
print("Rice Added = ",cart)
cart.insert(2, "Juice")
print("Juice was inserted at Index 2 in the Cart = ",cart)
cart.remove("Eggs")
print("Remove Eggs from the Cart = ",cart)
print("Total Items in the Cart = ",len(cart))
print("First 4 Items = ",cart[:4])
print("Last 2 Items = ",cart[-2:])
cart.sort()
print("After Sorting in Alphabetical Order = ",cart)
backup = cart.copy()
print("Backup = ",backup)